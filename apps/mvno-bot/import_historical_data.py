def import_data():
    """과거 데이터를 Firestore에 입력"""
    collection_ref = db.collection('mvno_records')
    
    success_count = 0
    error_count = 0
    
    for record in historical_data:
        try:
            doc_id = record['date']
            collection_ref.document(doc_id).set(record)
            print(f"✅ {doc_id} 저장 완료")
            success_count += 1
        except Exception as e:
            print(f"❌ {record['date']} 저장 실패: {e}")
            error_count += 1
    
    print(f"\n총 {success_count}개 성공, {error_count}개 실패")

